export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  try {
    const config = (await getSetting('orchestrator_config')) || {
      schedule_hours: ['06:30', '18:30'],
      approval_mode: 'full_auto',
      topic_mode: 'auto_pilot',
    };
    const queueData = (await getSetting('content_queue')) || { items: [] };
    const items = Array.isArray(queueData.items) ? queueData.items : [];

    // Find next pending item (approved or draft). If none exists, Coach Agent auto-creates one!
    let pendingItems = items.filter((item) => item.status === 'approved' || item.status === 'draft');
    if (pendingItems.length === 0) {
      const vnHour = (new Date().getUTCHours() + 7) % 24;
      const currentSlot = vnHour < 12 ? '06:30' : '18:30';
      const newItem = buildAutoGeneratedItem(currentSlot);
      items.unshift(newItem);
      pendingItems = [newItem];
    }

    const nextItem = pendingItems[0];
    const baseAppUrl = 'https://tpai-sales-crm.vercel.app';
    const mediaFullUrl = nextItem.media_url?.startsWith('http')
      ? nextItem.media_url
      : `${baseAppUrl}${nextItem.media_url || '/assets/content/card-nd30.png'}`;

    const thumbnailFullUrl = nextItem.thumbnail_url?.startsWith('http')
      ? nextItem.thumbnail_url
      : nextItem.thumbnail_url
      ? `${baseAppUrl}${nextItem.thumbnail_url}`
      : mediaFullUrl;

    const scheduleTimeStr = nextItem.scheduled_at
      ? new Date(nextItem.scheduled_at).toLocaleString('vi-VN', {
          timeZone: 'Asia/Ho_Chi_Minh',
          hour: '2-digit',
          minute: '2-digit',
          day: '2-digit',
          month: '2-digit',
          year: 'numeric',
        })
      : `${nextItem.scheduled_slot || '06:30'} Hôm nay`;

    const headerTitle = `🚀 <b>[AUTO-PILOT ${nextItem.scheduled_slot || '06:30'}] 13 AI AGENTS ĐÃ XUẤT BẢN BÀI MỚI!</b>`;

    const tgMessage = [
      headerTitle,
      `━━━━━━━━━━━━━━━━━━━━`,
      `📌 <b>Chủ đề:</b> <b>${nextItem.topic_title}</b>`,
      `🗓 <b>Khung giờ:</b> <code>${scheduleTimeStr}</code>`,
      `🤖 <b>Dây chuyền 13 Agents:</b> <i>${(nextItem.agents_chain || []).join(' → ')}</i>`,
      `🖼 <b>Media đính kèm:</b> <a href="${mediaFullUrl}">${nextItem.media_type === 'video_reels' ? '🎬 Xem Video Reels 9:16 (MP4)' : '🎨 Xem Ảnh Card Thiết Kế (PNG)'}</a>`,
      `━━━━━━━━━━━━━━━━━━━━`,
      `📝 <b>NỘI DUNG BÀI ĐĂNG (1-CLICK COPY):</b>\n`,
      nextItem.content_text.slice(0, 950) + (nextItem.content_text.length > 950 ? '...' : ''),
      `━━━━━━━━━━━━━━━━━━━━`,
      `🔗 <b>Kiểm tra trên App CRM:</b> <a href="${baseAppUrl}/crm">Mở Trung Tâm Chỉ Huy AI</a>`,
    ].join('\n');

    const tgRes = await fetch(`https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        chat_id: TELEGRAM_CHAT_ID,
        text: tgMessage,
        parse_mode: 'HTML',
        disable_web_page_preview: false,
      }),
    });
    const tgData = await tgRes.json();

    // Optional Facebook Fanpage Auto-Publish via Webhook (Make.com / Pabbly — Khuyên Dùng 100% Free)
    let fbWebhookResult = null;
    const isVideo = nextItem.media_type === 'video_reels';
    const effectiveImageUrl = isVideo ? mediaFullUrl : thumbnailFullUrl;

    if (config.fb_webhook_url) {
      try {
        const fbWebRes = await fetch(config.fb_webhook_url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            action: 'auto_publish',
            title: nextItem.topic_title,
            message: nextItem.content_text,
            content: nextItem.content_text,
            image_url: effectiveImageUrl,
            video_url: mediaFullUrl,
            url: mediaFullUrl,
            media_url: mediaFullUrl,
            thumbnail_url: thumbnailFullUrl,
            media_type: nextItem.media_type,
            page_id: config.fb_page_id || '809750085555882',
            scheduled_slot: nextItem.scheduled_slot,
            timestamp: new Date().toISOString(),
          }),
        });
        fbWebhookResult = { ok: fbWebRes.ok, status: fbWebRes.status };
      } catch (err) {
        fbWebhookResult = { ok: false, error: err.message };
      }
    }

    // Optional Facebook Fanpage Auto-Publish if Page ID & Token configured
    let fbResult = null;
    if (config.fb_page_id && config.fb_page_token) {
      try {
        const fbRes = await fetch(`https://graph.facebook.com/v19.0/${config.fb_page_id}/feed`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            message: nextItem.content_text,
            link: 'https://tpai-sales-crm.vercel.app',
            access_token: config.fb_page_token,
          }),
        });
        fbResult = await fbRes.json();
      } catch (e) {
        fbResult = { error: e.message };
      }
    }

    // Mark item as published in Supabase queue so Thầy sees the completed flow in CRM
    const idx = items.findIndex((item) => item.id === nextItem.id);
    if (idx !== -1) {
      items[idx].status = 'published';
      items[idx].published_at = new Date().toISOString();
      await saveSetting('content_queue', { items });
    }

    return res.status(200).json({
      success: true,
      mode: 'auto_published',
      dispatched_item: nextItem.id,
      topic_title: nextItem.topic_title,
      slot_time: nextItem.scheduled_slot,
      telegram_ok: Boolean(tgData.ok),
      facebook: fbResult,
    });
  } catch (error) {
    console.error('[Cron Orchestrator Error]:', error);
    return res.status(500).json({
      success: false,
      error: error.message || 'Lỗi thực thi Cron Orchestrator',
    });
  }
}
